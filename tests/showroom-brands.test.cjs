const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'showroom.html'), 'utf8');
const group = {innerHTML:'', inputs:[], querySelectorAll() { return this.inputs; }};
let renders = 0;
const context = {document:{getElementById:()=>group},render:()=>renders++};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,'assets/data.js'),'utf8'),context);
vm.runInContext(html.slice(html.indexOf('    const BRAND_LOGOS'),html.indexOf("    checkGroup('f-marcas'")),context);
vm.runInContext('const countBy=(key,value)=>CARROS.filter(c=>c[key]===value).length;',context);
const logos=vm.runInContext('BRAND_LOGOS',context);
for(const brand of vm.runInContext('MARCAS',context)) {
  assert(logos[brand],brand+': missing logo');
  assert(fs.existsSync(path.join(root,'assets/logos',logos[brand])),brand+': missing asset');
}
vm.runInContext("checkGroup('f-marcas',MARCAS,new Set(['Audi']),'marca')",context);
